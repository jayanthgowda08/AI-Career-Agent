"""
schemas/rag.py — Pydantic Schemas for RAG-based Career Guidance
"""

from typing import List, Optional
from pydantic import BaseModel, Field


class RAGQueryRequest(BaseModel):
    """Payload for asking a career question grounded in RAG documents."""
    question: str = Field(..., min_length=3, description="Candidate's career question")
    top_k: int = Field(default=3, ge=1, le=10, description="Number of context passages to retrieve")


class RAGSourceCitation(BaseModel):
    """Citation metadata for a retrieved document passage."""
    source_title: str
    source_type: str
    snippet: str
    similarity_score: float


class RAGQueryResponse(BaseModel):
    """Fact-grounded answer generated by Gemini using retrieved context."""
    question: str
    answer: str
    citations: List[RAGSourceCitation]
    retrieved_chunk_count: int
